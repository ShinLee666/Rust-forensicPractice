/// 按置换表对 nbits 位的整数做置换（表中第 i 项表示输出第 i 位来自输入第 table[i] 位）
fn permute(x: u64, table: &[u8], nbits: u32) -> u64 {
    let mut out = 0u64;
    for &p in table {
        out = (out << 1) | ((x >> (nbits - p as u32)) & 1);
    }
    out
}

/// Feistel 轮函数 f(R, K)：32 位 -> 48 位扩展 -> 异或子密钥 -> 8 个 S 盒 -> P 置换
fn f(r: u32, k: u64) -> u32 {
    let expanded = permute(r as u64, &E, 32) ^ k; // 48 位
    let mut out = 0u32;
    for i in 0..8 {
        let six = ((expanded >> (42 - 6 * i)) & 0x3F) as usize;
        let row = ((six & 0x20) >> 4) | (six & 1); // 第 1、6 位拼成行号
        let col = (six >> 1) & 0xF; // 中间 4 位为列号
        out = (out << 4) | SBOX[i][row * 16 + col] as u32;
    }
    permute(out as u64, &P, 32) as u32
}

/// 由 8 字节密钥生成 16 个 48 位子密钥
fn key_schedule(key: &[u8; 8]) -> [u64; 16] {
    let k = u64::from_be_bytes(*key);
    let k56 = permute(k, &PC1, 64);
    let mut c = (k56 >> 28) as u32; // 左半 28 位
    let mut d = (k56 & 0x0FFF_FFFF) as u32; // 右半 28 位
    let mut subkeys = [0u64; 16];
    for (i, &s) in SHIFTS.iter().enumerate() {
        // 28 位循环左移
        c = (c << s) | (c >> (28 - s));
        d = (d << s) | (d >> (28 - s));
        c &= 0x0FFF_FFFF;
        d &= 0x0FFF_FFFF;
        subkeys[i] = permute(((c as u64) << 28) | d as u64, &PC2, 56);
    }
    subkeys
}

/// 用给定子密钥序列处理一个 8 字节分组（加密为正序子密钥，解密为逆序）
fn des_block(block: &[u8], subkeys: &[u64; 16]) -> [u8; 8] {
    assert_eq!(block.len(), 8, "DES 分组必须为 8 字节");
    let x = u64::from_be_bytes(block.try_into().unwrap());
    let x = permute(x, &IP, 64);
    let mut l = (x >> 32) as u32;
    let mut r = (x & 0xFFFF_FFFF) as u32;
    for &k in subkeys {
        // 保存旧 R：L' = R，R' = L ^ f(R, K)
        let (nl, nr) = (r, l ^ f(r, k));
        l = nl;
        r = nr;
    }
    // 注意结尾不再交换，所以拼回去时是 (R16, L16)
    let out = permute(((r as u64) << 32) | l as u64, &IP_INV, 64);
    out.to_be_bytes()
}

// ---------------------------------------------------------------------------
// 公开接口：ECB 模式（无填充，数据长度必须是 8 的倍数）
// ---------------------------------------------------------------------------

/// DES-ECB 加密
pub fn des_encrypt_ecb(data: &[u8], key: &[u8; 8]) -> Vec<u8> {
    assert!(data.len() % 8 == 0 && !data.is_empty(), "DES-ECB 数据长度必须是 8 的非零倍数");
    let ks = key_schedule(key);
    data.chunks(8).flat_map(|c| des_block(c, &ks)).collect()
}

/// DES-ECB 解密
pub fn des_decrypt_ecb(data: &[u8], key: &[u8; 8]) -> Vec<u8> {
    assert!(data.len() % 8 == 0 && !data.is_empty(), "DES-ECB 数据长度必须是 8 的非零倍数");
    let mut ks = key_schedule(key);
    ks.reverse(); // 解密 = 逆序使用子密钥
    data.chunks(8).flat_map(|c| des_block(c, &ks)).collect()
}

/// 3DES-ECB（三密钥 EDE）加密：key 为 24 字节（K1 || K2 || K3）
pub fn tdes_encrypt_ecb(data: &[u8], key: &[u8; 24]) -> Vec<u8> {
    let k1: [u8; 8] = key[0..8].try_into().unwrap();
    let k2: [u8; 8] = key[8..16].try_into().unwrap();
    let k3: [u8; 8] = key[16..24].try_into().unwrap();
    des_encrypt_ecb(&des_decrypt_ecb(&des_encrypt_ecb(data, &k1), &k2), &k3)
}

/// 3DES-ECB（三密钥 EDE）解密：D_K1(E_K2(D_K3(x)))
pub fn tdes_decrypt_ecb(data: &[u8], key: &[u8; 24]) -> Vec<u8> {
    let k1: [u8; 8] = key[0..8].try_into().unwrap();
    let k2: [u8; 8] = key[8..16].try_into().unwrap();
    let k3: [u8; 8] = key[16..24].try_into().unwrap();
    des_decrypt_ecb(&des_encrypt_ecb(&des_decrypt_ecb(data, &k3), &k2), &k1)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(s: &str) -> Vec<u8> {
        (0..s.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
            .collect()
    }

    /// 经典 DES KAT：key=0123456789ABCDEF，明文 "Now is t"（4E6F772069732074）
    /// 密文 3FA40E8A984D4815
    #[test]
    fn des_known_answer() {
        let key: [u8; 8] = hex("0123456789ABCDEF").try_into().unwrap();
        let pt = hex("4E6F772069732074");
        let ct = des_encrypt_ecb(&pt, &key);
        assert_eq!(ct, hex("3FA40E8A984D4815"), "DES 加密不匹配");
        assert_eq!(des_decrypt_ecb(&ct, &key), pt, "DES 解密不匹配");
    }

    /// DES 另一组常用 KAT：key=133457799BBCDFF1，pt=0123456789ABCDEF -> 85E813540F0AB405
    #[test]
    fn des_kat2() {
        let key: [u8; 8] = hex("133457799BBCDFF1").try_into().unwrap();
        let pt = hex("0123456789ABCDEF");
        let ct = des_encrypt_ecb(&pt, &key);
        assert_eq!(ct, hex("85E813540F0AB405"));
        assert_eq!(des_decrypt_ecb(&ct, &key), pt);
    }

    /// 3DES-ECB 三密钥 KAT（NIST SP 800-20 示例风格）：
    /// key = 0123456789ABCDEFFEDCBA987654321089ABCDEF01234567
    /// pt  = "Now is the time for all "（24 字节，3 个分组）
    #[test]
    fn tdes_known_answer() {
        let key: [u8; 24] = hex("0123456789ABCDEFFEDCBA987654321089ABCDEF01234567")
            .try_into()
            .unwrap();
        let pt = b"Now is the time for all ".to_vec();
        let ct = tdes_encrypt_ecb(&pt, &key);
        assert_eq!(ct, hex("FBE62B683922941E0E05E3677C31FC264259965404D683DF"));
        assert_eq!(tdes_decrypt_ecb(&ct, &key), pt);
    }

    /// 多分组往返测试
    #[test]
    fn des_roundtrip_multiblock() {
        let key: [u8; 8] = hex("AABB09182736CCDD").try_into().unwrap();
        let data = hex("00112233445566778899AABBCCDDEEFF0123456789ABCDEF");
        let ct = des_encrypt_ecb(&data, &key);
        assert_eq!(des_decrypt_ecb(&ct, &key), data);
    }
}
